import { BaseEntity } from '../../../shared/domain/model/base-entity';
import { ActivityType } from './activity-type.enum';

/**
 * Registration of participants in an adventure camp.
 *
 * @summary Domain entity with who reserved, how many participants, the activity and the temperature when it was made.
 * @author Gerardo Palacin
 */
export class Reservation implements BaseEntity {
  readonly #id: number;
  readonly #adventureCampId: number;
  readonly #activityType: ActivityType;
  readonly #participantName: string;
  readonly #participants: number;
  readonly #weatherTemperature: number;
  readonly #reservedAt: Date;

  /**
   * @param id - Unique identifier generated by the server.
   * @param adventureCampId - Identifier of the reserved camp.
   * @param activityType - Activity reserved.
   * @param participantName - Name of the person who reserved.
   * @param participants - Number of participants.
   * @param weatherTemperature - Temperature in degrees Celsius when the reservation was made.
   * @param reservedAt - Date and time of the reservation.
   */
  constructor(
    id: number,
    adventureCampId: number,
    activityType: ActivityType,
    participantName: string,
    participants: number,
    weatherTemperature: number,
    reservedAt: Date
  ) {
    this.#id = id;
    this.#adventureCampId = adventureCampId;
    this.#activityType = activityType;
    this.#participantName = participantName;
    this.#participants = participants;
    this.#weatherTemperature = weatherTemperature;
    this.#reservedAt = reservedAt;
  }

  /** Unique identifier generated by the server. */
  get id(): number {
    return this.#id;
  }

  /** Identifier of the reserved camp. */
  get adventureCampId(): number {
    return this.#adventureCampId;
  }

  /** Activity reserved. */
  get activityType(): ActivityType {
    return this.#activityType;
  }

  /** Name of the person who reserved. */
  get participantName(): string {
    return this.#participantName;
  }

  /** Number of participants. */
  get participants(): number {
    return this.#participants;
  }

  /** Temperature in degrees Celsius when the reservation was made. */
  get weatherTemperature(): number {
    return this.#weatherTemperature;
  }

  /** Date and time of the reservation. */
  get reservedAt(): Date {
    return this.#reservedAt;
  }
}
